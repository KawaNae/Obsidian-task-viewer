/**
 * Timer target ID management: ensure, cleanup.
 */

import type { TimerInstance } from './TimerInstance';
import { describeTimerAnchor, isDailyTimer } from './TimerInstance';
import type { TimerContext } from './TimerContext';
import type { TimerStorageUtils } from './TimerStorageUtils';
import { isTvInline } from '../types';
import { logError, logWarn } from '../log/log';

export class TimerTargetManager {
    constructor(
        private ctx: TimerContext,
        private storageUtils: TimerStorageUtils,
    ) {}

    // ─── Ensure ──────────────────────────────────────────────

    async ensureTimerTargetId(timerId: string): Promise<void> {
        const timer = this.ctx.timers.get(timerId);
        if (!timer) return;
        // デイリーノート起点は対象行が無い。目印は自分が書いたレコード行の
        // `^id` が持つので、ここで足すものは無い。
        if (isDailyTimer(timer)) return;

        if (timer.timerTargetId) {
            timer.autoGeneratedTargetId = this.storageUtils.isAutoManagedTimerTargetId(timer.timerTargetId);
            this.ctx.persistTimersToStorage();
            return;
        }

        if (isTvInline(timer)) {
            await this.ensureInlineTimerTargetId(timer);
        }
    }

    private async ensureInlineTimerTargetId(timer: TimerInstance): Promise<void> {
        const taskIndex = this.ctx.plugin.getTaskIndex();
        // 開始のときに渡された名前で引く（開始を押したときの写し）。
        const currentTask = taskIndex.getTask(timer.taskId);
        if (!currentTask) {
            logWarn(`[TimerTargetManager] inline target not resolved at start, timer runs without an anchor (${describeTimerAnchor(timer)})`);
            return;
        }

        if (currentTask.anchor) {
            timer.taskId = currentTask.id;
            timer.taskFile = currentTask.file;
            timer.taskOriginalText = currentTask.originalText;
            timer.timerTargetId = currentTask.anchor;
            timer.autoGeneratedTargetId = this.storageUtils.isAutoManagedTimerTargetId(currentTask.anchor);
            this.ctx.persistTimersToStorage();
            return;
        }

        // 行の `^id` をほかの行も持っている。錨にならないので、足すこともできない。
        if (currentTask.blockId) {
            logWarn(`[TimerTargetManager] target ^${currentTask.blockId} is not the file's only one, timer runs without an anchor (${describeTimerAnchor(timer)})`);
            return;
        }

        const newTargetId = this.storageUtils.generateTimerTargetId();
        try {
            // 付けられなかった id を探しに行かない。理由は書き込みの層が通知済み。
            if (!(await taskIndex.updateTask(currentTask.id, { blockId: newTargetId }))) return;
            await taskIndex.waitForScan(currentTask.file);

            const updatedTask = taskIndex.getTaskByAnchor(currentTask.file, newTargetId);
            if (updatedTask) {
                timer.taskId = updatedTask.id;
                timer.taskFile = updatedTask.file;
                timer.taskOriginalText = updatedTask.originalText;
                timer.timerTargetId = newTargetId;
                timer.autoGeneratedTargetId = true;
                this.ctx.persistTimersToStorage();
            }
        } catch (error) {
            logError(`[TimerWidget] Failed to assign timer target ID for inline task: ${(error as Error)?.message ?? error}`);
        }
    }

    // ─── Cleanup ─────────────────────────────────────────────

    async cleanupGeneratedTargetId(timer: TimerInstance): Promise<void> {
        if (!timer.autoGeneratedTargetId) return;
        if (!timer.timerTargetId) return;
        if (!this.storageUtils.isAutoManagedTimerTargetId(timer.timerTargetId)) return;
        if (this.hasAnotherActiveTimerWithTarget(timer.timerTargetId)) return;

        if (isTvInline(timer)) {
            await this.removeInlineTimerTargetId(timer, timer.timerTargetId);
        }
    }

    private hasAnotherActiveTimerWithTarget(timerTargetId: string): boolean {
        for (const timer of this.ctx.timers.values()) {
            if (timer.timerTargetId === timerTargetId) {
                return true;
            }
        }
        return false;
    }

    private async removeInlineTimerTargetId(timer: TimerInstance, anchor: string): Promise<void> {
        const taskIndex = this.ctx.plugin.getTaskIndex();
        const targetTask = taskIndex.getTaskByAnchor(timer.taskFile, anchor);
        if (!targetTask) return;

        try {
            await taskIndex.updateTask(targetTask.id, { blockId: undefined });
            await taskIndex.waitForScan(targetTask.file);
        } catch (error) {
            logError(`[TimerWidget] Failed to remove inline timer target ID: ${(error as Error)?.message ?? error}`);
        }
    }
}
